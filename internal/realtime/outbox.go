// OutboxPayload is the JSON stored in outbox_events.payload_json.
//
// The table columns already carry id, room_id, event_sequence and type, so the
// payload holds only what those columns do not: the versions, the resource hint
// and the visibility filter. Keeping the audience server-side is deliberate: it
// must never be serialised into a client message, and putting it in a separate
// column would tempt someone to expose it in a projection.
type OutboxPayload struct {
	RoomVersion  int64    `json:"roomVersion"`
	PhaseVersion int64    `json:"phaseVersion,omitempty"`
	Resource     Resource `json:"resource,omitempty"`
	RoundID      string   `json:"roundId,omitempty"`
	Reason       string   `json:"reason,omitempty"`
	Audience     Audience `json:"audience,omitempty"`
	// RevokeMembershipID is a server-only delivery instruction, never wire data.
	RevokeMembershipID string `json:"revokeMembershipId,omitempty"`
	// MembershipID supports revocations committed by older V2 builds.
	MembershipID string `json:"membershipId,omitempty"`
}

// AppendEvent writes one outbox row inside the caller's transaction.
//
// This is the only sanctioned way to schedule a notification. It takes an
// *sql.Tx rather than a *storage.DB on purpose: the row must be part of the same
// transaction as the business write it describes , so that a
// committed fact and its notification either both exist or neither does. Passing
// the transaction in makes it impossible to accidentally write the outbox row on
// a different connection, which is the mistake that produces "broadcast without a
// commit".
//
// eventID must be unique per logical event and is what a client deduplicates on;
// eventSequence must be monotonically increasing per room (the unique index
// idx_outbox_room_seq enforces it).
func AppendEvent(ctx context.Context, tx *sql.Tx, eventID, roomID string, eventSequence int64, msgType MessageType, payload OutboxPayload) error {
	if tx == nil {
		return errors.New("realtime: AppendEvent requires a transaction")
	}
	if err := checkID("eventId", eventID); err != nil {
		return err
	}
	if err := checkID("roomId", roomID); err != nil {
		return err
	}
	if eventSequence < 0 {
		return fmt.Errorf("realtime: negative eventSequence %d", eventSequence)
	}
	switch msgType {
	case TypeStateChanged, TypePhaseChanged, TypePresenceChange:
	default:
		// session.revoked and resync.required are generated by the hub, never by a
		// business write. hello and pong are per-connection.
		return fmt.Errorf("realtime: outbox cannot carry message type %q", msgType)
	}
	body, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("realtime: encode outbox payload: %w", err)
	}
	_, err = tx.ExecContext(ctx, `
		INSERT INTO outbox_events (id, room_id, event_sequence, type, payload_json, created_at)
		VALUES (?, ?, ?, ?, ?, ?)`,
		eventID, roomID, eventSequence, string(msgType), string(body), time.Now().UTC().UnixMilli())
	if err != nil {
		return fmt.Errorf("realtime: insert outbox event: %w", err)
	}
	return nil
}

// NextEventSequence returns the next free sequence for a room.
//
// It must be called inside the same transaction that inserts the row, otherwise
// two concurrent writers can pick the same number and the unique index turns the
// race into a failed commit. The caller passes its *sql.Tx so the read and the
// insert share one snapshot.
func NextEventSequence(ctx context.Context, tx *sql.Tx, roomID string) (int64, error) {
	var next sql.NullInt64
	err := tx.QueryRowContext(ctx,
		`SELECT COALESCE(MAX(event_sequence), 0) + 1 FROM outbox_events WHERE room_id = ?`,
		roomID).Scan(&next)
	if err != nil {
		return 0, fmt.Errorf("realtime: next event sequence: %w", err)
	}
	if !next.Valid || next.Int64 < 1 {
		return 1, nil
	}
	return next.Int64, nil
}

// outboxRow is one pending row read from the outbox.
type outboxRow struct {
	id      string
	roomID  string
	seq     int64
	msgType MessageType
	payload OutboxPayload
	created time.Time
	rawJSON string
}

// Dispatcher turns committed outbox rows into notifications.
//
// Delivery contract :
//
// - The dispatcher only ever reads through the *read* pool. In WAL mode a reader
// sees committed data only, so a row that is still inside an open write
// transaction is invisible. "Never broadcast before commit" is therefore a
// structural property of the query, not a discipline someone has to remember.
// - At-least-once. A row is marked dispatched only after the fan-out call
// returned. A crash, a panic or a failed mark re-delivers the same row, and
// because the row id is the eventId, the client discards the duplicate. The
// server never claims exactly-once and never uses the ack cursor to prune.
// - Ordering within a room is by event_sequence, which the query enforces.
type Dispatcher struct {
	db  *storage.DB
	hub *Hub
	cfg Config

	// markFailure is a test seam: when non-nil and it returns an error, the
	// dispatched_at update is skipped, which reproduces the crash window that makes
	// redelivery possible.
	markFailure func(id string) error
	// publishHook is a test seam invoked after a successful fan-out.
	publishHook func(eventID string)

	published atomic.Int64
	errors    atomic.Int64
	lagMax    atomic.Int64

	startOnce sync.Once
	stopOnce  sync.Once
	stop      chan struct{}
	stopped   chan struct{}
	wg        sync.WaitGroup
}

// NewDispatcher builds a dispatcher bound to one database and one hub.
func NewDispatcher(db *storage.DB, hub *Hub, cfg Config) (*Dispatcher, error) {
	if db == nil {
		return nil, errors.New("realtime: dispatcher requires a database")
	}
	if hub == nil {
		return nil, errors.New("realtime: dispatcher requires a hub")
	}
	cfg = cfg.withDefaults()
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	return &Dispatcher{
		db:      db,
		hub:     hub,
		cfg:     cfg,
		stop:    make(chan struct{}),
		stopped: make(chan struct{}),
	}, nil
}

// Start launches the polling loop. It is safe to call once.
func (d *Dispatcher) Start() {
	d.startOnce.Do(func() {
		d.wg.Add(1)
		go d.loop()
	})
}

// Stop ends the loop and waits for it.
func (d *Dispatcher) Stop() {
	d.stopOnce.Do(func() {
		close(d.stop)
	})
	d.wg.Wait()
}

// loop polls for committed rows.
func (d *Dispatcher) loop() {
	defer d.wg.Done()
	defer close(d.stopped)
	t := time.NewTicker(d.cfg.OutboxPollInterval)
	defer t.Stop()
	for {
		select {
		case <-d.stop:
			return
		case <-t.C:
			// A dispatch error must not kill the loop: the next tick retries the
			// same rows, which is exactly the at-least-once behaviour we want.
			_, _ = d.DispatchOnce(context.Background())
		case <-d.hub.closeCh:
			return
		}
	}
}

// DispatchOnce performs one poll cycle and reports how many rows were published.
//
// It is exported so a test (or a supervisor that wants deterministic scheduling)
// can drive the dispatcher without timers.
func (d *Dispatcher) DispatchOnce(ctx context.Context) (int, error) {
	rows, err := d.pending(ctx, d.cfg.OutboxBatch)
	if err != nil {
		d.errors.Add(1)
		d.hub.metrics.Counter(MetricDispatchErrors, 1)
		return 0, err
	}
	if len(rows) == 0 {
		return 0, nil
	}

	published := 0
	var firstErr error
	for _, row := range rows {
		if err := d.publishRow(row); err != nil {
			d.errors.Add(1)
			d.hub.metrics.Counter(MetricDispatchErrors, 1)
			if firstErr == nil {
				firstErr = err
			}
			// Do not mark it dispatched: the next cycle retries, which is the
			// at-least-once guarantee. Continuing with the remaining rows keeps one
			// poisoned row from blocking the room forever.
			continue
		}
		published++
		if d.markFailure != nil {
			if err := d.markFailure(row.id); err != nil {
				// Simulated crash between publish and mark: leave dispatched_at NULL.
				if firstErr == nil {
					firstErr = err
				}
				continue
			}
		}
		if err := d.markDispatched(ctx, row.id); err != nil {
			d.errors.Add(1)
			if firstErr == nil {
				firstErr = err
			}
			continue
		}
		d.published.Add(1)
		d.hub.metrics.Counter(MetricPublished, 1)
		lag := time.Since(row.created)
		if lag > 0 {
			d.lagMax.Store(lag.Milliseconds())
			d.hub.metrics.Gauge(MetricDispatchLagMillis, lag.Milliseconds())
		}
		if d.publishHook != nil {
			d.publishHook(row.id)
		}
	}
	return published, firstErr
}

// pending reads committed, undispatched rows in sequence order.
//
// The read pool is used, not the write pool, and the rows are read fully before
// the transaction is released: no cursor or connection is held across a socket
// write .
func (d *Dispatcher) pending(ctx context.Context, limit int) ([]outboxRow, error) {
	rows, err := d.db.Read().QueryContext(ctx, `
		SELECT id, room_id, event_sequence, type, payload_json, created_at
		FROM outbox_events
		WHERE dispatched_at IS NULL
		ORDER BY room_id, event_sequence
		LIMIT ?`, limit)
	if err != nil {
		return nil, fmt.Errorf("realtime: read outbox: %w", err)
	}
	defer rows.Close()

	out := make([]outboxRow, 0, limit)
	for rows.Next() {
		var (
			r       outboxRow
			typ     string
			payload string
			created int64
		)
		if err := rows.Scan(&r.id, &r.roomID, &r.seq, &typ, &payload, &created); err != nil {
			return nil, fmt.Errorf("realtime: scan outbox row: %w", err)
		}
		r.msgType = MessageType(typ)
		r.rawJSON = payload
		r.created = time.UnixMilli(created).UTC()
		if payload != "" {
			if err := json.Unmarshal([]byte(payload), &r.payload); err != nil {
				// A corrupt payload must not stop the room. Log the id and skip it so
				// it can be inspected; it stays undispatched, which makes it visible
				// in the pending index rather than silently discarded.
				d.errors.Add(1)
				continue
			}
		}
		out = append(out, r)
	}
	return out, rows.Err()
}

// publishRow fans one row out to the hub.
func (d *Dispatcher) publishRow(row outboxRow) error {
	target := row.payload.RevokeMembershipID
	if row.msgType == TypeSessionRevoked {
		// Legacy room writes incorrectly used a connection-level type for a
		// room-wide notification. Never broadcast or replay that terminal event.
		target = row.payload.MembershipID
		if target == "" {
			return errors.New("realtime: legacy revocation has no target membership")
		}
		row.msgType = TypeStateChanged
		row.payload.Resource = ResourceRoom
	}
	if target != "" {
		// A delayed outbox row must not disconnect a member who has since
		// legitimately rejoined with the same membership ID.
		var active int
		if err := d.db.Read().QueryRow(`SELECT COUNT(*) FROM memberships WHERE id=? AND room_id=? AND left_at IS NULL`, target, row.roomID).Scan(&active); err != nil {
			return fmt.Errorf("realtime: check revoked membership: %w", err)
		}
		if active == 0 {
			d.hub.RevokeMembership(row.roomID, target, "authorization-changed")
		}
	}
	return d.hub.Publish(Publication{
		EventID:      row.id,
		Type:         row.msgType,
		RoomID:       row.roomID,
		RoomVersion:  row.payload.RoomVersion,
		PhaseVersion: row.payload.PhaseVersion,
		Seq:          row.seq,
		Resource:     row.payload.Resource,
		RoundID:      row.payload.RoundID,
		Reason:       row.payload.Reason,
		Audience:     row.payload.Audience,
	})
}

// markDispatched records delivery.
//
// Losing this update only costs a duplicate notification, which is why it is safe
// to do after the fan-out and why the write is not retried in a tight loop.
func (d *Dispatcher) markDispatched(ctx context.Context, id string) error {
	_, err := d.db.Write().ExecContext(ctx,
		`UPDATE outbox_events SET dispatched_at = ? WHERE id = ? AND dispatched_at IS NULL`,
		time.Now().UTC().UnixMilli(), id)
	if err != nil {
		return fmt.Errorf("realtime: mark outbox %s dispatched: %w", id, err)
	}
	return nil
}

// PruneDispatched deletes dispatched rows older than the retention window.
//
// forbids the outbox growing without bound; this keeps a short correlation
// window and then drops the rows. Undispatched rows are never touched.
func (d *Dispatcher) PruneDispatched(ctx context.Context) (int64, error) {
	cutoff := time.Now().UTC().Add(-d.cfg.OutboxRetention).UnixMilli()
	res, err := d.db.Write().ExecContext(ctx,
		`DELETE FROM outbox_events WHERE dispatched_at IS NOT NULL AND dispatched_at < ?`, cutoff)
	if err != nil {
		return 0, fmt.Errorf("realtime: prune outbox: %w", err)
	}
	n, _ := res.RowsAffected()
	return n, nil
}

// Stats reports dispatcher counters for tests and metrics.
type DispatchStats struct {
	Published int64
	Errors    int64
	LagMaxMS  int64
}

// Stats returns a snapshot of the counters.
func (d *Dispatcher) Stats() DispatchStats {
	return DispatchStats{
		Published: d.published.Load(),
		Errors:    d.errors.Load(),
		LagMaxMS:  d.lagMax.Load(),
	}
}

// Backlog reports how many rows are committed but not yet dispatched. Operators
// watch this number .
func (d *Dispatcher) Backlog(ctx context.Context) (int64, error) {
	var n int64
	err := d.db.Read().QueryRowContext(ctx,
		`SELECT COUNT(*) FROM outbox_events WHERE dispatched_at IS NULL`).Scan(&n)
	if err != nil {
		return 0, fmt.Errorf("realtime: count outbox backlog: %w", err)
	}
	return n, nil
}
